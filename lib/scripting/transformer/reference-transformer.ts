import { replace } from 'estraverse'
import type { Expression, Identifier, MemberExpression, Program } from 'estree'
import { logger } from '../../util/logger.js'
import type { EnumsApi } from '../../vpt/enums.js'
import type { GlobalApi } from '../../vpt/global-api.js'
import type { Table } from '../../vpt/table/table.js'
import { callExpression, identifier, memberExpression } from '../estree.js'
import type { Stdlib } from '../stdlib/index.js'
import { Transformer } from './transformer.js'

interface HasPropName {
	_getPropertyName(name: string): string | undefined
}

function getPropName(obj: unknown, name: string): string | undefined {
	return (obj as HasPropName)?._getPropertyName?.(name)
}

/** VBS scope roots: the program and every function. */
function isScopeRoot(node: any): boolean {
	return node.type === 'Program' || node.type === 'FunctionDeclaration' || node.type === 'FunctionExpression'
}

/**
 * VBScript-legal identifiers that are reserved words (or illegal bindings in
 * strict mode, like `arguments`) in JavaScript. Matching is case-insensitive
 * because VBScript is. Deliberately absent: `null` (the VBS `Null` literal
 * maps to `__stdlib.Null` before this runs, and `Dim null` cannot parse),
 * `eval` (generated by `replaceExecuteGlobal`, which runs after this), and
 * words the grammar rejects (`let`, `function`, `new`, `class`, ...).
 */
const RESERVED_WORD_RENAMES: Record<string, string> = {
	switch: 'aSwitch',
	var: 'aVar',
	this: 'aThis',
	typeof: 'aTypeof',
	delete: 'aDelete',
	return: 'aReturn',
	break: 'aBreak',
	continue: 'aContinue',
	throw: 'aThrow',
	try: 'aTry',
	catch: 'aCatch',
	void: 'aVoid',
	instanceof: 'aInstanceof',
	super: 'aSuper',
	extends: 'aExtends',
	import: 'aImport',
	export: 'aExport',
	debugger: 'aDebugger',
	finally: 'aFinally',
	yield: 'aYield',
	await: 'aAwait',
	enum: 'aEnum',
	implements: 'aImplements',
	interface: 'aInterface',
	package: 'aPackage',
	protected: 'aProtected',
	static: 'aStatic',
	arguments: 'aArguments',
}

/**
 * Renames identifiers that are legal in VBScript but reserved in JavaScript
 * (`switch`, `var`, `this`, ...), which would otherwise generate unparseable
 * JS (`let switch;`). Member and method names are valid JS even when reserved,
 * so those positions are skipped. Shared by the transformer pipeline and the
 * grammar's `vbsToJs`, so both emit parseable JS.
 */
export function renameReservedWords(ast: Program): void {
	replace(ast, {
		enter: (node, parent: any) => {
			if (node.type !== 'Identifier') {
				return node
			}
			if (Transformer.isReservedName(node.name)) {
				return node
			}
			if (parent?.type === 'MemberExpression' && parent.property === node && !parent.computed) {
				return node
			}
			if (
				(parent?.type === 'MethodDefinition' || parent?.type === 'Property') &&
				parent.key === node &&
				!parent.computed
			) {
				return node
			}
			const renamed = RESERVED_WORD_RENAMES[node.name.toLowerCase()]
			if (!renamed) {
				return node
			}
			node.name = renamed
			return node
		},
	})
}

/**
 * In the Visual Pinball table script, everything is global. In JavaScript we
 * decided to properly manage the scope in order not to pollute the global
 * namespace.
 *
 * This transformer goes through all variables and determines to which of the
 * following name spaces it belongs to (in that order):
 *   - items: table elements
 *   - enums: enum values exposed in Visual Pinball's VBScript API
 *   - stdlib: the VBScript Standard Library implemented in JavaScript
 *   - global: reference to Visual Pinball's global API
 *   - eval: `ExecuteGlobal()` calls are directly handled here because they
 *     cannot be wrapped into another method without losing the current
 *     execution context.
 *
 * To match a namespace, the transformer looks at the actual values of each
 * name space. That's possible because at compile time, the table and the
 * player are already set up and thus accessible.
 *
 * To match an object or property, the transformer uses a special API that
 * allows matching in a case-insensitive way. When matched, the resulting
 * identifier is properly cased.
 *
 * Examples:
 *   - `BallRelease.CreateBall()` would become `__items.BallRelease.CreateBall()`.
 *   - `ImageAlignment.ImageAlignWorld` would become `__enums.ImageAlignment.ImageAlignWorld`.
 *   - `PlaySound()` would become `__global.PlaySound()`.
 */
export class ReferenceTransformer extends Transformer {
	private readonly table: Table
	private readonly itemApis: Record<string, unknown>
	private readonly enumApis: EnumsApi
	private readonly globalApi: GlobalApi
	private readonly stdlib: Stdlib

	constructor(
		ast: Program,
		table: Table,
		itemApis: Record<string, unknown>,
		enumApis: EnumsApi,
		globalApi: GlobalApi,
		stdlib: Stdlib,
	) {
		super(ast, true)
		this.table = table
		this.itemApis = itemApis
		this.enumApis = enumApis
		this.globalApi = globalApi
		this.stdlib = stdlib
	}

	public transform(): Program {
		this.addScope()
		this.replaceNamespacedNames(this.ast)
		this.replaceReservedWords(this.ast)
		this.replaceGetRef(this.ast)
		this.replaceExecuteGlobal(this.ast)
		return this.ast
	}

	/**
	 * Element/enum/stdlib/global lookups in a single traversal (previously
	 * one `replace` pass per namespace). Identifiers resolve on enter in
	 * pass order (element, bare enum value, stdlib, global); qualified enum
	 * member expressions resolve on leave so an element-named enum object
	 * keeps element priority, as when the element pass ran first.
	 */
	public replaceNamespacedNames(ast: Program): void {
		const assigned = this.collectAssignedNames(ast)
		const roots: object[] = []
		replace(ast, {
			enter: (node, parent: any) => {
				if (isScopeRoot(node)) {
					roots.push(node)
				}
				const root = roots[roots.length - 1]
				return this.replaceIdentifierReference(
					node,
					parent,
					root === undefined ? undefined : assigned.get(root),
				)
			},
			leave: (node, parent: any) => {
				const out = this.replaceEnumReference(node, parent)
				if (isScopeRoot(node)) {
					roots.pop()
				}
				return out
			},
		})
	}

	/** Bare-identifier chain (element, bare enum value, then stdlib, then global). */
	private replaceIdentifierReference(node: any, parent: any, assigned?: Set<string>): any {
		node = this.replaceElementReference(node, parent)
		node = this.replaceBareEnumReference(node, parent, assigned)
		node = this.replaceStdlibReference(node, parent)
		return this.replaceGlobalApiReference(node, parent)
	}

	private bareEnumMembers?: Map<string, { enumName: string; propName: string } | null>

	/** Bare member name → its enum, or null when several enums share the name. Built once per transformer. */
	private buildBareEnumMembers(): Map<string, { enumName: string; propName: string } | null> {
		const members = new Map<string, { enumName: string; propName: string } | null>()
		const api = this.enumApis as unknown as {
			_getPropertyNames(): string[]
			[key: string]: unknown
		}
		for (const enumName of api._getPropertyNames()) {
			const enumObj = api[enumName] as { _getPropertyNames?: () => string[] } | undefined
			for (const propName of enumObj?._getPropertyNames?.() ?? []) {
				const key = propName.toLowerCase()
				members.set(key, members.has(key) ? null : { enumName, propName })
			}
		}
		return members
	}

	/** Lower-cased bare member name → its enum. */
	private findBareEnumMember(name: string): { enumName: string; propName: string } | undefined {
		this.bareEnumMembers ??= this.buildBareEnumMembers()
		return this.bareEnumMembers.get(name.toLowerCase()) ?? undefined
	}

	/**
	 * Script-assigned bare names per scope root. VBS creates a variable on
	 * assignment, so a name written anywhere in a scope is scope-owned: bare
	 * reads must not resolve to an enum. This also keeps `For`/`For Each`
	 * counters scope-bound, since the loop lowering assigns them without
	 * declaring.
	 */
	private collectAssignedNames(ast: Program): Map<object, Set<string>> {
		const assigned = new Map<object, Set<string>>()
		const roots: object[] = []
		replace(ast, {
			enter: (node: any) => {
				if (isScopeRoot(node)) {
					roots.push(node)
				}
				const target =
					node.type === 'AssignmentExpression'
						? node.left
						: node.type === 'ForOfStatement'
							? node.left
							: node.type === 'UpdateExpression'
								? node.argument
								: undefined
				if (target?.type === 'Identifier') {
					const root = roots[roots.length - 1]
					if (root !== undefined) {
						let names = assigned.get(root)
						if (!names) {
							names = new Set()
							assigned.set(root, names)
						}
						names.add(target.name.toLowerCase())
					}
				}
				return node
			},
			leave: (node: any) => {
				if (isScopeRoot(node)) {
					roots.pop()
				}
				return node
			},
		})
		return assigned
	}

	/**
	 * Rewrites bare COM type-library constants (`SeqRandom`, `SeqAllOff`)
	 * to their enum (`__enums.SequencerState.SeqRandom`). Native exposes the
	 * IDL enums as script globals; previously only the qualified form was
	 * rewritten, so bare names read as undefined and silently disabled
	 * sequencer effects. Elements keep priority (checked first); locals win
	 * via {@link Transformer.isLocalVariable}. Assignment targets are left
	 * alone so a write can never corrupt the shared enum singleton, and
	 * member names colliding across enums stay unresolved.
	 */
	private replaceBareEnumReference(node: any, parent: any, assigned?: Set<string>): any {
		if (!this.isEligible(node, parent)) {
			return node
		}
		if (parent?.type === 'AssignmentExpression' && parent.left === node) {
			return node
		}
		// A name assigned anywhere in this scope is scope-owned (VBS creates
		// the variable on assignment), so its reads must not resolve to an
		// enum. This also shields `For`/`For Each` counters, which the loop
		// lowering assigns without declaring.
		if (assigned?.has(node.name.toLowerCase())) {
			return node
		}
		const hit = this.findBareEnumMember(node.name)
		if (!hit) {
			return node
		}
		return memberExpression(
			memberExpression(identifier(Transformer.ENUMS_NAME), identifier(hit.enumName)),
			identifier(hit.propName),
		)
	}

	/**
	 * Adds the scope as argument to the GetRef call so we can actually retrieve the reference.
	 * @param ast
	 */
	public replaceGetRef(ast: Program): void {
		replace(ast, {
			enter: (node, _parent: any) => {
				if (node.type === 'CallExpression') {
					if (
						node.callee.type === 'MemberExpression' &&
						node.callee.object.type === 'Identifier' &&
						node.callee.object.name === ReferenceTransformer.STDLIB_NAME &&
						node.callee.property.type === 'Identifier' &&
						node.callee.property.name.toLowerCase() === 'getref'
					) {
						node.arguments.push(identifier(ReferenceTransformer.SCOPE_NAME))
					}
				}
				return node
			},
		})
	}

	private replaceElementReference(node: any, parent: any): any {
		if (!this.isEligible(node, parent)) {
			return node
		}

		// table items are no functions
		if (parent && parent.type === 'FunctionDeclaration') {
			return node
		}

		// now check the item name
		const elementName = this.table.getElementApiName((node as Identifier).name)
		if (!elementName) {
			return node
		}

		// patch property
		if (parent.property?.name) {
			const propName = getPropName(this.itemApis[elementName], parent.property.name)
			if (propName) {
				parent.property.name = propName
			}
		}
		return memberExpression(identifier(Transformer.ITEMS_NAME), identifier(elementName))
	}

	private replaceEnumReference(node: any, parent: any): any {
		const isFunction = parent && parent.type === 'CallExpression'
		const isIdentifier =
			node.type === 'MemberExpression' && node.object.type === 'Identifier' && node.property.type === 'Identifier'
		if (isIdentifier && !isFunction) {
			const enumNode = node as MemberExpression
			const enumObject = enumNode.object as Identifier
			const enumProperty = enumNode.property as Identifier
			const enumName = this.enumApis._getPropertyName(enumObject.name)
			let propName: string | undefined
			if (enumName) {
				propName = getPropName(
					(this.enumApis as unknown as Record<string, unknown>)[enumName],
					enumProperty.name,
				)
				if (propName) {
					enumNode.object = memberExpression(identifier(Transformer.ENUMS_NAME), identifier(enumName))
					enumProperty.name = propName
				} else {
					logger().warn(`[scripting] Unknown value "${enumProperty.name}" of enum ${enumName}.`)
				}
			}
		}
		return node
	}

	private replaceGlobalApiReference(node: any, parent: any): any {
		if (!this.isEligible(node, parent)) {
			return node
		}

		// now, check the global namespace
		const name = this.globalApi._getPropertyName((node as Identifier).name)
		if (!name) {
			return node
		}

		return memberExpression(identifier(Transformer.GLOBAL_NAME), identifier(name))
	}

	/**
	 * Renames identifiers that are legal in VBScript but reserved in JavaScript.
	 * Runs after every namespace lookup so a table element (or enum/global/
	 * stdlib member) named e.g. `Switch` keeps resolving while only genuinely
	 * unresolved identifiers are renamed.
	 */
	public replaceReservedWords(ast: Program): void {
		renameReservedWords(ast)
	}

	private replaceStdlibReference(node: any, parent: any): any {
		if (!this.isEligible(node, parent)) {
			return node
		}

		// check the name in stdlib's namespace
		const name = this.stdlib._getPropertyName((node as Identifier).name)
		if (!name) {
			return node
		}
		// patch property
		if (parent.property?.name && (this.stdlib as unknown as Record<string, unknown>)[name]) {
			const propName = getPropName(
				(this.stdlib as unknown as Record<string, unknown>)[name],
				parent.property.name,
			)
			if (propName) {
				parent.property.name = propName
			}
		}

		// add player object to activeX instantiation
		if (name === 'CreateObject' && parent?.type === 'CallExpression' && parent.callee === node) {
			parent.arguments.push(identifier(Transformer.PLAYER_NAME))
		}
		return memberExpression(identifier(Transformer.STDLIB_NAME), identifier(name))
	}

	private isEligible(node: any, parent: any): boolean {
		// only look at identifiers
		if (node.type !== 'Identifier') {
			return false
		}

		// if part of a member, must be the object (the left part).
		if (parent && parent.type === 'MemberExpression' && parent.object !== node) {
			return false
		}

		// skip already known nodes
		if (this.isKnown(node, parent)) {
			return false
		}

		// no locally declared variables either
		return !this.isLocalVariable(node)
	}

	/**
	 * The `eval()` command can't be wrapped into a function, because it messes
	 * up the execution context. So we transpile and execute directly.
	 *
	 * Example:
	 *    ExecuteGlobal GetTextFile("controller.vbs")
	 * becomes:
	 *    eval(__vbsHelper.transpileInline(__global.GetTextFile('controller.vbs')));
	 *
	 * @param ast
	 */
	public replaceExecuteGlobal(ast: Program): void {
		replace(ast, {
			enter: (node, _parent: any) => {
				if (node.type === 'CallExpression') {
					if (
						node.callee.type === 'Identifier' &&
						['executeglobal', 'execute', 'eval'].includes(node.callee.name.toLowerCase())
					) {
						node.callee.name = 'eval'
						const args = [node.arguments[0] as Expression]

						// if it's a "getTextFile", we want to know which and pass it to the transpiler
						if (isCallToGetTextFile(node)) {
							args.push((node as any).arguments[0].arguments[0])
						}
						node.arguments[0] = callExpression(
							memberExpression(identifier(Transformer.VBSHELPER_NAME), identifier('transpileInline')),
							args,
						)
					}
				}
				return node
			},
		})
	}
}

function isCallToGetTextFile(node: any): boolean {
	return (
		node.arguments.length > 0 &&
		node.arguments[0].type === 'CallExpression' &&
		node.arguments[0].callee.property &&
		node.arguments[0].callee.property.type === 'Identifier' &&
		node.arguments[0].callee.property.name === 'GetTextFile' &&
		node.arguments[0].arguments.length > 0 &&
		node.arguments[0].arguments[0].type === 'Literal'
	)
}
